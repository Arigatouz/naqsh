function tpl(
  name: string,
  category: Category,
  w: number,
  h: number,
  bg: Partial<Background>,
  elements: DesignElement[],
): Template {
  const { filter, ...rest } = bg;
  return {
    id: name,
    name,
    category,
    project: {
      id: `tpl-${name}`,
      name,
      updatedAt: 0,
      w,
      h,
      bg: { ...defaultBg(Boolean(bg.transparent)), ...rest, filter: { ...identityFilter(), ...filter } },
      elements,
    },
  };
}

